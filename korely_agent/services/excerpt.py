"""The sentences of a long text that a question is about (1.0.31).

The context block cuts a memory too long for its room after its first whole
sentences (`context._whole_sentences_within`, 1.0.30). On an agent's notes
the answer is rarely there: on 16 Nov 2026, twenty questions with a known
answer read against a team's 459 notes, the sentence that answered began
between 23% and 97% of its note, and four of the nine wrong answers had the
note with the answer third to fifth by the search, shown by an opening that
did not hold the answer or not at all.

The rule is the query-biased summary: a text is shown by the sentences that
hold the words of the question, never by a piece of a sentence.
  * Tombros and Sanderson, "Advantages of Query Biased Summaries in
    Information Retrieval" (SIGIR 1998, read on 16 Nov 2026), section 2.4:
    a sentence is scored by the query terms it holds, and "the summary for
    each document was then generated by outputting the top-scoring
    sentences, until a desired summary length was reached"; abstract: "the
    use of query biased summaries significantly improves both the accuracy
    and speed of user relevance judgements".
  * Turpin, Tsegay, Hawking and Williams, "Fast Generation of Result
    Snippets in Web Search" (SIGIR 2007, read the same day), section 4:
    "Previous work on summarization identifies the sentence as the minimal
    unit for extraction and presentation to the user", and "all sentences
    in a document should be ranked against the query, and the top two or
    three returned as the snippet".
Here the length is the room the caller gives; the sentences come in the
order of the text, a mark where sentences between them were left out; and
when every sentence that holds a word of the question is in, the room left
goes to the sentences next to the best one, the ones after it first (the
paper does not say which sentences of no score to take, nor in what order
the chosen ones are printed: both are ours).

A word of the question weighs by how few of the texts shown with this one
hold it (`weights`): a word every one of them holds tells no sentence from
another, so no list of words to ignore is written here, in any language.
Sparck Jones ("A Statistical Interpretation of Term Specificity and Its
Application in Retrieval", Journal of Documentation 28(1), 1972, abstract,
read on 16 Nov 2026): "terms should be weighted according to collection
frequency, so that matches on less frequent, more specific, terms are of
greater value than matches on frequent terms". The weight is the one of
Robertson and Zaragoza ("The Probabilistic Relevance Framework: BM25 and
Beyond", 2009, section 3.1, equation 3.3, read the same day), log((N - n +
0.5) / (n + 0.5)) for a word in n of N texts, with one added inside the
logarithm so that it is never negative, as Apache Lucene computes it
(BM25Similarity.idf).

What a word is, in every script (`terms`). A run of letters, digits and
their marks is a word, compared by its letters: compatibility forms, case
and nonspacing marks aside (NFKD and case folding, Unicode Standard Annex
#15; the marks dropped are the category Mn, so "İstanbul" meets "istanbul"
and an Arabic word meets itself written with its vowel marks; dropping them
is ours). A script that writes no space between words has no such run:
there the terms are the pairs of characters next to each other, with no
dictionary (Kwok, "Lexicon Effects on Chinese Information Retrieval", 1997,
ACL Anthology W97-0316, read on 16 Nov 2026: "In bigram representation of
text, no lexicon is used", ranking 2,125 of 2,182 relevant documents
against 2,015 for the short-word method on TREC-5). Which characters those
are is read from the Unicode Character Database, never from a list of
languages: the line-breaking class SA ("Runs of these characters require
morphological analysis to determine break opportunities", Unicode Standard
Annex #14, section 5.1; LineBreak-14.0.0.txt, the ranges below), and the
wide characters of East Asia (`unicodedata.east_asian_width`, W and F, of
the character's compatibility form: the ideographs, the kana, and the
Hangul syllables, which Korean does separate with spaces and are paired
all the same). A run that passes from one kind
to the other is two (a Latin name glued to ideographs).

What this is not. It chooses which sentences of a text ALREADY found are
shown; which texts are found stays the search's, by meaning (the cosine of
the vectors). Words match as written, the forms above aside: an inflected
form, a synonym, a question in another language than the text do not
match. Then nothing is chosen (`sentences_about` answers None) and the
caller shows what it showed before. The sentence found by meaning is the
larger step on the same road (1.0.33, off by default: a vector for each
window of a long memory, services/memory_windows.py): the same choice of
sentences, scored by the window a search found the memory by
(`sentences_scored`).

Dependency: the standard library only. Where a sentence ends is the
caller's (memory_core `sentences`, Unicode's default sentence boundary).
"""
from __future__ import annotations

import bisect
import math
import unicodedata
from typing import Callable, Dict, Iterable, List, Optional, Sequence, Tuple

# Line_Break=SA, LineBreak-14.0.0.txt (unicode.org/Public/14.0.0/ucd), its
# 122 entries joined where they touch: Thai, Lao, Myanmar, Khmer, Tai Le,
# New Tai Lue, Tai Tham, Tai Viet, Ahom. First and last code point of each.
_SA = (
    (0x0E01, 0x0E3A), (0x0E40, 0x0E4E), (0x0E81, 0x0E82), (0x0E84, 0x0E84), (0x0E86, 0x0E8A),
    (0x0E8C, 0x0EA3), (0x0EA5, 0x0EA5), (0x0EA7, 0x0EBD), (0x0EC0, 0x0EC4), (0x0EC6, 0x0EC6),
    (0x0EC8, 0x0ECD), (0x0EDC, 0x0EDF), (0x1000, 0x103F), (0x1050, 0x108F), (0x109A, 0x109F),
    (0x1780, 0x17D3), (0x17D7, 0x17D7), (0x17DC, 0x17DD), (0x1950, 0x196D), (0x1970, 0x1974),
    (0x1980, 0x19AB), (0x19B0, 0x19C9), (0x19DA, 0x19DA), (0x19DE, 0x19DF), (0x1A20, 0x1A5E),
    (0x1A60, 0x1A7C), (0x1AA0, 0x1AAD), (0xA9E0, 0xA9EF), (0xA9FA, 0xA9FE), (0xAA60, 0xAAC2),
    (0xAADB, 0xAADF), (0x11700, 0x1171A), (0x1171D, 0x1172B), (0x1173A, 0x1173B), (0x1173F, 0x11746),
)
_SA_FIRST = [a for a, _b in _SA]

#: What stands where sentences were left out: before the first one shown,
#: when it is not the text's first, and between two that are not neighbours.
LEFT_OUT_BEFORE = "… "
LEFT_OUT_BETWEEN = " … "


def _without_spaces(ch: str) -> bool:
    """Whether `ch` belongs to a script that writes no space between words
    (the module's docstring: Line_Break=SA, or wide in East Asia)."""
    cp = ord(ch)
    i = bisect.bisect_right(_SA_FIRST, cp) - 1
    if i >= 0 and cp <= _SA[i][1]:
        return True
    # Of its compatibility form: a full-width Latin letter is a Latin
    # letter, a half-width katakana a katakana.
    form = unicodedata.normalize("NFKC", ch)
    return bool(form) and unicodedata.east_asian_width(form[0]) in ("W", "F")


def _folded(piece: str) -> str:
    """`piece` as it is compared: NFKD, case folded, NFKD again (a fold can
    compose), without its nonspacing marks and format characters."""
    form = unicodedata.normalize("NFKD", unicodedata.normalize("NFKD", piece).casefold())
    return "".join(ch for ch in form if unicodedata.category(ch) not in ("Mn", "Cf"))


def _runs(text: str) -> Iterable[Tuple[bool, List[int], int, int]]:
    """The runs of letters and digits of `text`, their marks and format
    characters inside them, in order: (whether the run's script is written
    without spaces, where each of its letters or digits begins, its start,
    its end). A run that passes from one kind to the other is two. One pass
    over the text."""
    n = len(text)
    i = 0
    while i < n:
        if unicodedata.category(text[i])[0] not in "LN":
            i += 1
            continue
        kind = _without_spaces(text[i])
        starts = [i]            # where each letter or digit of the run begins
        j = i + 1
        while j < n:
            cat = unicodedata.category(text[j])
            if cat[0] in "LN":
                if _without_spaces(text[j]) != kind:
                    break
                starts.append(j)
            elif cat[0] != "M" and cat != "Cf":
                break
            j += 1
        yield kind, starts, i, j
        i = j


def terms(text: str) -> List[Tuple[str, int, int]]:
    """The terms of `text`, each with where it begins and ends in `text`:
    its words, and for the scripts written without spaces the pairs of
    characters next to each other (a character alone when it has no
    neighbour). One pass over the text."""
    out: List[Tuple[str, int, int]] = []
    for kind, starts, i, j in _runs(text):
        if not kind:
            form = _folded(text[i:j])
            if form:
                out.append((form, i, j))
        else:
            units = [_folded(text[a:b]) for a, b in zip(starts, starts[1:] + [j])]
            if len(units) == 1:
                if units[0]:
                    out.append((units[0], i, j))
            for k in range(len(units) - 1):
                if units[k] and units[k + 1]:
                    out.append((units[k] + units[k + 1], starts[k],
                                starts[k + 2] if k + 2 < len(starts) else j))
    return out


def units(text: str) -> List[Tuple[int, int]]:
    """Where each word of `text` begins and ends, in any script: a run of
    letters and digits (`_runs`), or, in a script written without spaces,
    which has no word to count by, a pair of letters next to each other
    with their marks, the last one alone when a run has an odd number: the
    bigram of the module's docstring (Kwok 1997), here without overlap, a
    count and not a term. No dictionary. What the windows of a long memory
    are counted in (services/memory_windows.py). One pass."""
    out: List[Tuple[int, int]] = []
    for kind, starts, i, j in _runs(text):
        if not kind:
            out.append((i, j))
        else:
            ends = starts[1:] + [j]
            out.extend((starts[k], ends[min(k + 1, len(starts) - 1)])
                       for k in range(0, len(starts), 2))
    return out


def weights(question: str, texts: Iterable[str]) -> Dict[str, float]:
    """What each term of `question` weighs among `texts`, the texts shown
    together: the fewer of them hold it, the more (the module's docstring:
    ln(1 + (N - n + 0.5) / (n + 0.5)), N texts and n of them holding the
    term). A term none of them holds weighs nothing here: it can choose no
    sentence."""
    asked = {t for t, _s, _e in terms(question or "")}
    if not asked:
        return {}
    held = [{t for t, _s, _e in terms(x or "")} & asked for x in texts]
    total = len(held)
    out: Dict[str, float] = {}
    for t in asked:
        n = sum(1 for h in held if t in h)
        if n:
            out[t] = math.log(1.0 + (total - n + 0.5) / (n + 0.5))
    return out


def sentences_about(text: str, ends: Sequence[int], weigh: Dict[str, float], most: int,
                    cost: Callable[[str], int] = lambda s: len(s.encode("utf-8")),
                    ) -> Optional[List[Tuple[int, int]]]:
    """The whole sentences of `text` that hold the most of the question, as
    runs (start, end) in the order of the text, which `joined` writes in at
    most `most` units of `cost` (UTF-8 bytes), its marks counted. `ends`:
    where each sentence of `text` ends, in order, the end of the text last.

    The sentences that hold a term of `weigh`, heaviest first (the distinct
    terms a sentence holds, their weights added; the earlier one first among
    equals), each taken when it still fits; then the sentences after the
    run of the heaviest one taken, and the ones before it, while they fit.
    None when no sentence holds a term, or none of those fits.

    A run ends where its last sentence's words do, the spaces after them
    dropped. Linear in the text but for sorting the sentences that hold a
    term: every cost is read from sums kept by place, and a run's ends are
    kept at its ends, never searched for."""
    if not weigh or most <= 0 or not text:
        return None
    spans = sentence_spans(text, ends)
    if not spans:
        return None
    return sentences_scored(text, spans, scores_of(text, spans, weigh), most, cost)


def scores_of(text: str, spans: Sequence[Tuple[int, int]], weigh: Dict[str, float]) -> List[float]:
    """How much of the question each sentence of `text` (`spans`) holds: the
    weights (`weights`) of the distinct terms of the question it holds,
    added."""
    score = [0.0] * len(spans)
    s = 0
    seen: set = set()
    for term, at, _e in terms(text):
        while s < len(spans) and at >= spans[s][1]:
            s += 1
            seen = set()
        if s >= len(spans):
            break
        if term in weigh and term not in seen:
            seen.add(term)
            score[s] += weigh[term]
    return score


def _positive(score) -> bool:
    """A score above zero: a number, or a tuple of them (`sentences_scored`)
    whose first component that is not zero is above it."""
    if isinstance(score, tuple):
        return next((x > 0 for x in score if x), False)
    return score > 0


def _descending(score):
    """The sort key that puts a higher score first, a tuple compared
    component by component."""
    return tuple(-x for x in score) if isinstance(score, tuple) else -score


def sentence_spans(text: str, ends: Sequence[int]) -> List[Tuple[int, int]]:
    """(start, end) of each sentence of `text`, from where each ends
    (`ends`, in order, the end of the text last), the spaces after one
    belonging to it."""
    spans: List[Tuple[int, int]] = []
    a = 0
    for e in ends:
        if a < e <= len(text):
            spans.append((a, e))
            a = e
    return spans


def sentences_scored(text: str, spans: Sequence[Tuple[int, int]], score: Sequence[float],
                     most: int, cost: Callable[[str], int] = lambda s: len(s.encode("utf-8")),
                     ) -> Optional[List[Tuple[int, int]]]:
    """The choice of `sentences_about` for sentences already scored: `spans`
    (`sentence_spans`) and a score for each, of any origin (the question's
    words, or the characters of the window a search found the text by,
    services/context.py, 1.0.33). A score is a number or a tuple of numbers,
    compared component by component. The sentences of a score above zero,
    highest first, each taken when it still fits; then the ones next to the
    run of the first taken, after it, then before it. None when none scores,
    or none fits."""
    k = len(spans)
    if not k or most <= 0 or len(score) != k:
        return None
    begin, stop = [], []      # each sentence without the spaces around it
    for a, e in spans:
        while e > a and text[e - 1].isspace():
            e -= 1
        while a < e and text[a].isspace():
            a += 1
        begin.append(a)
        stop.append(e)
    ranked = sorted((i for i in range(k) if _positive(score[i])),
                    key=lambda i: (_descending(score[i]), i))
    if not ranked:
        return None
    upto = [0] * (len(text) + 1)
    for i, ch in enumerate(text):
        upto[i + 1] = upto[i] + cost(ch)
    before, between = cost(LEFT_OUT_BEFORE), cost(LEFT_OUT_BETWEEN)

    def run(i: int, j: int) -> int:
        return upto[stop[j]] - upto[begin[i]]

    # The first sentence that has words: before it nothing is left out.
    head = next((i for i in range(k) if begin[i] < stop[i]), 0)
    taken = [False] * k
    first = list(range(k))   # at a run's last sentence: its first
    last = list(range(k))    # at a run's first sentence: its last
    body, runs = 0, 0

    def take(i: int) -> bool:
        nonlocal body, runs
        lo = first[i - 1] if i > 0 and taken[i - 1] else i
        hi = last[i + 1] if i + 1 < k and taken[i + 1] else i
        new = body + run(lo, hi)
        joins = runs + 1
        if lo < i:
            new -= run(lo, i - 1)
            joins -= 1
        if hi > i:
            new -= run(i + 1, hi)
            joins -= 1
        whole = new + between * (joins - 1) + (0 if lo == head or taken[head] else before)
        if whole > most:
            return False
        taken[i] = True
        first[hi], last[lo] = lo, hi
        body, runs = new, joins
        return True

    best = None
    for i in ranked:
        if take(i) and best is None:
            best = i
    if best is None:
        return None
    # The room left goes to the sentences next to the best one taken: the
    # ones after its run, then the ones before it. `first` and `last` are
    # kept at a run's two ends, so the run is read from its first sentence.
    lo = best
    while lo > 0 and taken[lo - 1]:
        lo -= 1
    hi = last[lo]
    while hi + 1 < k and take(hi + 1):
        hi = last[lo]
    while lo > 0 and take(lo - 1):
        lo = first[hi]
    out: List[Tuple[int, int]] = []
    i = 0
    while i < k:
        if taken[i]:
            j = last[i]
            out.append((begin[i], stop[j]))
            i = j + 1
        else:
            i += 1
    return out


def joined(text: str, runs: Sequence[Tuple[int, int]]) -> str:
    """The runs of `sentences_about` as one line of words: the sentences in
    the text's order, LEFT_OUT_BEFORE when the first is not the text's
    first, LEFT_OUT_BETWEEN where sentences were left out between two."""
    body = LEFT_OUT_BETWEEN.join(text[a:b] for a, b in runs)
    return (LEFT_OUT_BEFORE if runs and text[:runs[0][0]].strip() else "") + body
