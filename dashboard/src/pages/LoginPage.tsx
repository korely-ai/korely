import { useEffect, useRef, useState } from "react";
import { useLocation, useNavigate } from "react-router";

import { useAuth } from "@/contexts/AuthContext";
import { returnTarget } from "@/lib/returnTo";

/**
 * A username and a password, against this machine.
 *
 * There are no sign-in buttons here because there is no identity provider: a
 * private install authenticates people against its own database. The first
 * account is made on the box with
 *
 *     docker compose exec api python -m korely_agent.manage \
 *       create-operator --tenant <id> --username anna
 *
 * which generates a password, prints it once and stores the hash. There is no
 * default to change afterwards, which is the whole reason it works that way.
 */
export function LoginPage() {
  const { user, loading, authError, login } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const target = returnTarget(location.state);
  const [username, setUsername] = useState("");
  const [password, setPassword] = useState("");
  const [busy, setBusy] = useState(false);
  const first = useRef<HTMLInputElement>(null);

  useEffect(() => {
    if (!loading && user) navigate(target, { replace: true });
  }, [loading, user, navigate, target]);

  useEffect(() => {
    first.current?.focus();
  }, []);

  useEffect(() => {
    if (authError) setBusy(false);
  }, [authError]);

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (busy) return;
    setBusy(true);
    try {
      // The password is trimmed too. These are generated by the install and
      // pasted, and a trailing space picked up by the copy is the commonest
      // reason a correct password is refused. The generated alphabet has no
      // spaces in it, so nothing legitimate is lost.
      await login(username.trim(), password.trim());
    } catch {
      // AuthContext already turned it into a sentence; the effect above stops
      // the spinner.
    }
  };

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-[#0B0F17]">
        <p className="text-[#9CA3AF] text-sm">Loading…</p>
      </div>
    );
  }

  return (
    <div className="min-h-screen flex items-center justify-center bg-[#0B0F17] px-4">
      <div className="w-full max-w-[380px]">
        <h1 className="text-[#E2E8ED] text-2xl font-semibold mb-1">Korely</h1>
        <p className="text-[#9CA3AF] text-sm mb-8">
          Memory for your agents, on this machine.
        </p>

        <form onSubmit={submit} className="space-y-4">
          <div>
            <label
              htmlFor="username"
              className="block text-[13px] text-[#9CA3AF] mb-1.5"
            >
              Username
            </label>
            <input
              id="username"
              ref={first}
              value={username}
              onChange={(e) => setUsername(e.target.value)}
              autoComplete="username"
              autoCapitalize="none"
              spellCheck={false}
              required
              className="w-full rounded-lg bg-white/4 border border-white/10 px-3 py-2.5 text-[#E2E8ED] text-[15px] outline-hidden focus:border-[#3B82F6]/60"
            />
          </div>

          <div>
            <label
              htmlFor="password"
              className="block text-[13px] text-[#9CA3AF] mb-1.5"
            >
              Password
            </label>
            <input
              id="password"
              type="password"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              autoComplete="current-password"
              required
              className="w-full rounded-lg bg-white/4 border border-white/10 px-3 py-2.5 text-[#E2E8ED] text-[15px] outline-hidden focus:border-[#3B82F6]/60"
            />
          </div>

          {authError && (
            <p role="alert" className="text-[13px] text-[#F87171]">
              {authError}
            </p>
          )}

          {/* Dark ink on this blue, lighter on hover, as the dashboard's dark
              theme writes its buttons: white on it read 3.7:1, under the
              4.5:1 of WCAG 2.2 (pre-tester check of 15 Nov 2026;
              tests/test_the_screen_reads_in_both_themes.py). */}
          <button
            type="submit"
            disabled={busy || !username.trim() || !password.trim()}
            className="w-full rounded-lg bg-[#3B82F6] hover:bg-[#60A5FA] disabled:opacity-40 disabled:hover:bg-[#3B82F6] text-[#0F172A] text-[15px] font-medium py-2.5 transition-colors"
          >
            {busy ? "Signing in…" : "Sign in"}
          </button>
        </form>

        <p className="mt-8 text-[12px] text-[#8E96A4] leading-relaxed">
          No account yet? Make one on the machine itself:
          <code className="block mt-1.5 text-[#9CA3AF] font-mono text-[11px] break-all">
            docker compose exec api python -m korely_agent.manage create-operator
            --tenant &lt;id&gt; --username &lt;name&gt;
          </code>
        </p>
      </div>
    </div>
  );
}
